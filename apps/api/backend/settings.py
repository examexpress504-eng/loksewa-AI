def _env_bool(name, default=False):
    """Read a boolean env var. Unset OR empty falls back to `default`."""
    raw = (os.environ.get(name) or '').strip()
    if not raw:
        return default
    return raw.lower() in ('1', 'true', 'yes', 'on')


