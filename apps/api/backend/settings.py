# EMAIL_HOST unset (the default, including local dev) means Django uses the
# console backend - emails print to the server log/terminal instead of
# actually sending, so the flow is fully testable with zero external
# credentials. Set EMAIL_HOST (+ EMAIL_HOST_USER/PASSWORD) to send real mail
# through Resend's SMTP relay (smtp.resend.com).
#
# Resend's SMTP relay uses implicit SSL on port 465, not STARTTLS - set
# EMAIL_USE_SSL=True (default) rather than EMAIL_USE_TLS for it. The two are
# mutually exclusive; EMAIL_USE_TLS only applies if EMAIL_USE_SSL is unset/false.
EMAIL_HOST = os.environ.get('EMAIL_HOST', '').strip()
if EMAIL_HOST:
    EMAIL_BACKEND = 'django.core.mail.backends.smtp.EmailBackend'
    EMAIL_PORT = int(os.environ.get('EMAIL_PORT', '465'))
    EMAIL_HOST_USER = os.environ.get('EMAIL_HOST_USER', '')
    EMAIL_HOST_PASSWORD = os.environ.get('EMAIL_HOST_PASSWORD', '')
    # Smart TLS/SSL resolution:
    # - Port 587 uses STARTTLS (standard for Gmail SMTP: smtp.gmail.com)
    # - Port 465 uses SSL (Resend SMTP relay: smtp.resend.com)
    # Explicit env vars EMAIL_USE_TLS / EMAIL_USE_SSL override port defaults.
    _raw_ssl = os.environ.get('EMAIL_USE_SSL')
    _raw_tls = os.environ.get('EMAIL_USE_TLS')
    if _raw_tls is not None and _env_bool('EMAIL_USE_TLS', False):
        EMAIL_USE_TLS = True
        EMAIL_USE_SSL = False
    elif _raw_ssl is not None and _env_bool('EMAIL_USE_SSL', False):
        EMAIL_USE_SSL = True
        EMAIL_USE_TLS = False
    else:
        if EMAIL_PORT == 587:
            EMAIL_USE_TLS = True
            EMAIL_USE_SSL = False
        else:
            EMAIL_USE_SSL = True
            EMAIL_USE_TLS = False
